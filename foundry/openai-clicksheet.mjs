#!/usr/bin/env node
// ECZ-ID Plugin Foundry: the copy/paste sheet for the OpenAI submission form.
//
// Generated from the same facts as the packages and read back out of the built
// archives, so a value in the sheet cannot drift from the value in the ZIP.
// Public URLs are never invented: a page that does not exist is marked
// PENDING_PUBLIC_PAGE with the exact URL to create.
//
// Usage: node foundry/openai-clicksheet.mjs [--dir <dir>] [--out <file>]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { zipRead } from "./zip.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const facts = JSON.parse(readFileSync(join(here, "product-facts.json"), "utf8"));
const defs = JSON.parse(readFileSync(join(here, "plugins.json"), "utf8"));

const arg = (flag, fallback) => {
  const i = process.argv.indexOf(flag);
  return i > 0 ? resolve(process.argv[i + 1]) : fallback;
};
const DIR = arg("--dir", join(root, "dist", "openai"));
const OUT = arg("--out", join(root, "dist", "openai", "OPENAI_BATCH_CLICK_SHEET.md"));

/** Live-page facts, probed on the date below. Anything false is PENDING_PUBLIC_PAGE. */
const PROBED = "2026-09-03";
const LEGAL_SLUG = {
  "eczid-mcp-verifier": "mcp-verifier",
  "eczid-mcp-trust": "mcp-trust",
  "eczid-agent-trust": "agent-trust",
  "eczid-api-trust": "api-trust",
  "eczid-dora-readiness": "dora-readiness",
  "eczid-sbom-cra-readiness": "sbom-cra-readiness"
};
// Only the SBOM/CRA pages returned 200 when probed. The others must not borrow them.
const LEGAL_LIVE = new Set(["eczid-sbom-cra-readiness"]);

const legalUrl = (id, kind) => {
  const url = `${facts.urls.gateway}/plugins/${LEGAL_SLUG[id]}/${kind}/`;
  return LEGAL_LIVE.has(id) ? url : `PENDING_PUBLIC_PAGE  (create: ${url})`;
};

const L = [];
const p = (...lines) => L.push(...lines);

p(`# OPENAI BATCH CLICK SHEET — Wave 1, the other five (${PROBED})`,
  "",
  "Copy/paste values for the OpenAI plugin submission form, one section per plugin.",
  "Generated by `foundry/openai-clicksheet.mjs` from the built archives — every value below is the value inside the ZIP.",
  "",
  `Publisher: **${facts.organisation.name}** · estate ${facts.organisation.estateUrl} · licence ${facts.organisation.license}.`,
  "",
  "**Read first**",
  "",
  "- Upload the ZIP of the same name from this directory. Do not rebuild or edit it by hand.",
  "- `PENDING_PUBLIC_PAGE` means that page does not exist yet. **Do not paste another product's URL in its place.** The SBOM & CRA legal URLs belong to SBOM & CRA only.",
  "- OpenAI requires a verified publisher identity and Apps Management write access before a draft can be submitted.",
  "- All five submissions are **skills-only**: no MCP server is declared, so no MCP URL, no `/.well-known/openai-apps-challenge` token and no demo credentials are needed.",
  "- OpenAI's form asks for **release notes** (initial submission or update, changes since the previous version, reviewer setup information). Text is given per plugin below.",
  "");

for (const def of defs.plugins) {
  if (!def.openai?.submit) continue;
  const file = join(DIR, `${def.id}-openai-SUBMISSION-READY.zip`);
  if (!existsSync(file)) throw new Error(`missing package: ${file}`);
  const entries = zipRead(readFileSync(file)).entries;
  const manifest = JSON.parse(entries.find((e) => e.name === ".codex-plugin/plugin.json").data.toString("utf8"));
  const i = manifest.interface;
  const o = def.openai;

  p(`---`, "", `## ${def.displayName}`, "",
    `**Upload:** \`${def.id}-openai-SUBMISSION-READY.zip\``, "",
    "| Form field | Paste this |",
    "|---|---|",
    `| Name | ${i.displayName} |`,
    `| Subtitle / short description | ${i.shortDescription} |`,
    `| Category | ${i.category} |`,
    `| Developer name | ${i.developerName} |`,
    `| Website URL | ${i.websiteURL} |`,
    `| Support URL | ${legalUrl(def.id, "support")} |`,
    `| Privacy policy URL | ${legalUrl(def.id, "privacy")} |`,
    `| Terms URL | ${legalUrl(def.id, "terms")} |`,
    `| Version | ${manifest.version} |`,
    `| Package name | ${manifest.name} |`,
    `| Capabilities | ${i.capabilities.join(", ")} |`,
    `| Plugin type | Skills only (no MCP server) |`,
    "",
    "**Description (long)**", "", "```", i.longDescription, "```", "",
    "**Starter prompts (3)**", "",
    ...o.starterPrompts.map((s, n) => `${n + 1}. ${s}`), "",
    "**Positive test cases (5)**", "",
    "| # | User prompt | Expected behaviour |",
    "|---|---|---|",
    ...o.positiveTests.map((t, n) => `| ${n + 1} | ${t.prompt} | ${t.expect} |`),
    "",
    "**Negative test cases (3)**", "",
    "| # | User prompt | Expected refusal or safe fallback |",
    "|---|---|---|",
    ...o.negativeTests.map((t, n) => `| ${n + 1} | ${t.prompt} | ${t.expect} |`),
    "",
    "**Test fixture / account** — none. No account, sign-in, credential or network access is needed. Point the plugin at any local repository; the review reads file names and paths only.",
    "",
    "**Release notes**", "", "```",
    `Initial submission. ${def.displayName} ${manifest.version}, skills-only.`,
    `Skill: ${def.skills.join(", ")}.`,
    o.longDescription,
    "No account, no sign-in, no network call, no telemetry. Reviews read file names and paths in the workspace the user points at; no file is opened and nothing is written. No credentials or fixture data are required to test.",
    "```", "");
}

p("---", "",
  "## The pages that must exist first",
  "",
  `Probed live on ${PROBED}. Website URLs are live for all five. Support, privacy and terms are not.`,
  "",
  "| Plugin | Support | Privacy | Terms |",
  "|---|---|---|---|",
  ...defs.plugins.filter((d) => d.openai?.submit).map((d) =>
    `| ${d.displayName} | \`${facts.urls.gateway}/plugins/${LEGAL_SLUG[d.id]}/support/\` | \`${facts.urls.gateway}/plugins/${LEGAL_SLUG[d.id]}/privacy/\` | \`${facts.urls.gateway}/plugins/${LEGAL_SLUG[d.id]}/terms/\` |`),
  "",
  `Fifteen pages, following the pattern the SBOM & CRA deployment already established at \`${facts.urls.gateway}/plugins/sbom-cra-readiness/{support,privacy,terms}/\` (all three verified 200 on ${PROBED}).`,
  "");

writeFileSync(OUT, L.join("\n"));
console.log(`click sheet -> ${OUT}`);
